#!/bin/bash
if test "$#" -lt 1; then
    echo "$0 <passgen cli path>"
    echo "Runs tests against the passgen binary."
    echo
    echo "Example:"
    echo "    mkdir build"
    echo "    cmake -S . -B build"
    echo "    cmake --build build"
    echo "    ./scripts/test-passgen-cli.sh ./build/src/cli/passgen"
    exit 0
fi
set -euxo pipefail

# which binary to test
passgen=$@

# don't let the configuration of whoever runs this influence the tests
tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT
export HOME="$tmpdir/home"
export XDG_CONFIG_HOME="$tmpdir/config"
unset XDG_CONFIG_PATH
mkdir -p "$HOME" "$XDG_CONFIG_HOME"

function matches() {
    grep -E "^$1$"
}

# things that should fail, and not print anything to standard output
function fails() {
    local output
    if output="$("$@" 2>/dev/null)"; then
        echo "expected failure: $*"
        exit 1
    fi
    test -z "$output"
}

function pattern_matches() {
    $passgen "$1" | matches "$1"
}

# writing to /dev/null works. with seccomp, checking whether the output is a
# terminal (which the C library does for character devices such as this one)
# used to kill the process.
$passgen "a" > /dev/null
$passgen -r zero "a" > /dev/null 2>&1
fails $passgen "[" 2> /dev/null

# test simple grammar
pattern_matches "a"
pattern_matches "a?"
pattern_matches "a{2}"
pattern_matches "a{1,2}"
pattern_matches "abc"
pattern_matches "abc|def"
pattern_matches "(abc)"
pattern_matches "(abc){2}"
pattern_matches "(abc){1,2}"
pattern_matches "(abc|def)"
pattern_matches "(abc|def){2}"
pattern_matches "(abc|def){1,2}"
pattern_matches "[a]"
pattern_matches "[ab]"
pattern_matches "[a-z]"
pattern_matches "[a-zA-Z0-9#]"
pattern_matches "[a-zA-Z0-9#]{2}"
pattern_matches "[a-zA-Z0-9#]{1,2}"

# characters with a meaning in patterns can be escaped
test "$($passgen 'a\(b\)\[c\]\{d\}e\|f\?')" = "a(b)[c]{d}e|f?"
$passgen '[\]\[\-]{8}' | matches '[][-]{8}'
$passgen '[+-\-]{8}' | matches '[+,-]{8}'

# test presets
$passgen -p apple1
$passgen -p apple2
$passgen -p firefox
$passgen -p uuid
$passgen -p edge

# test options
$passgen --amount 5 "a"
$passgen -a 5 "a"

$passgen --null "a"
$passgen -z "a"

$passgen --entropy "a"
$passgen -e "a"

$passgen --random "xorshift:1234" "a"
$passgen --random "zero" "a"
$passgen --random "system" "a"

# test flags
$passgen --version
$passgen -v

$passgen --help
$passgen -h

$passgen --list
$passgen -l

# output is not limited in length
test "$($passgen "a{1000}" | tr -d '\n' | wc -c)" -eq 1000
test "$($passgen -a 3 "[a-z]{500}" | wc -l)" -eq 3

# large outputs work when only little memory may be locked. the subshell keeps
# the limit from applying to the rest of the tests, and this is skipped where
# the limit cannot be set to this value. it takes more than the default
# limit of steps.
if (ulimit -l 8192) 2> /dev/null; then
    test "$(ulimit -l 8192; $passgen -S 20000000 "a{20000000}" | tr -d '\n' | wc -c)" -eq 20000000
fi

# deterministic randomness sources always produce the same output
test "$($passgen -r xorshift:1234 "[a-z]{32}")" = "$($passgen -r xorshift:1234 "[a-z]{32}")"
test "$($passgen -r zero "[a-z]{8}")" = "aaaaaaaa"

# every preset generates what the reference implementation says it should.
# this table is generated by `scripts/reference-vectors.py --cli`.
while read -r preset expected; do
    test "$($passgen -r xorshift:1234 -p "$preset")" = "$expected"
done << EOF
apple1 3t8-jsO-2Mo-COm
apple2 3t8Qjs-w2MoCO-mGr6ix
uuid b378ad68-a262-4c80-856c-b0cc9fe064be
edge 27OM1KAME5fEfAD
firefox x3t8QjsOw2MoCOm
proquint16 gupik
proquint32 gupik-fosab
proquint48 gupik-fosab-kabas
proquint64 gupik-fosab-kabas-vahuv
proquint80 gupik-fosab-kabas-vahuv-kuhif
proquint96 gupik-fosab-kabas-vahuv-kuhif-kufaf
proquint112 gupik-fosab-kabas-vahuv-kuhif-kufaf-zazut
proquint128 gupik-fosab-kabas-vahuv-kuhif-kufaf-zazut-gaboz
EOF
test "$($passgen --list | wc -l)" -eq 13

# master passphrase mode is deterministic, and depends on all of its inputs.
# these only work when built with monocypher (the default).
key="000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f"
if $passgen -r "chacha20:$key" "a" > /dev/null 2>&1; then
    a="$($passgen -m master -d example.com -t user -p apple2)"
    test "$a" = "$($passgen -m master -d example.com -t user -p apple2)"
    test "$a" != "$($passgen -m other -d example.com -t user -p apple2)"
    test "$a" != "$($passgen -m master -d example.org -t user -p apple2)"
    test "$a" != "$($passgen -m master -d example.com -t admin -p apple2)"

    # known answer, to notice when the derivation changes (which would change
    # everyone's passwords).
    test "$a" = "ZKYX4F-p3hvOg-dGx2es"

    # a randomness source from the configuration does not get in the way
    echo "random zero" > "$XDG_CONFIG_HOME/passgen.conf"
    test "$a" = "$($passgen -m master -d example.com -t user -p apple2)"
    rm "$XDG_CONFIG_HOME/passgen.conf"

    # but giving one on the command line is a mistake, as are a domain or a
    # token without a master passphrase
    fails $passgen -m master -r zero "a"
    fails $passgen -r zero -m master "a"
    fails $passgen -d example.com "a"
    fails $passgen -t user "a"

    # deriving the key needs more memory than may commonly be locked
    if (ulimit -l 8192) 2> /dev/null; then
        test "$a" = "$(ulimit -l 8192; $passgen -m master -d example.com -t user -p apple2)"
    fi

    # the key and IV of chacha20 are exactly 64 and 16 hex digits, and the
    # default IV is `passgen` followed by a zero byte.
    test "$($passgen -r "chacha20:$key" "[a-z]{16}")" = \
        "$($passgen -r "chacha20:$key:7061737367656e00" "[a-z]{16}")"
    test "$($passgen -r "chacha20:$key" "[a-z]{16}")" != \
        "$($passgen -r "chacha20:$key:0000000000000000" "[a-z]{16}")"
    fails $passgen -r "chacha20:key" "a"
    fails $passgen -r "chacha20:${key}0" "a"
    fails $passgen -r "chacha20:$key:" "a"
    fails $passgen -r "chacha20:$key:00000000" "a"

    # overlong keys are rejected
    long="$(printf 'A%.0s' $(seq 1 300))"
    fails $passgen -r "chacha20:$long" "a"
    fails $passgen -r "chacha20-argon2:$long" "a"
else
    # without monocypher, the options for master passphrase mode do not
    # exist, so using them is an error rather than being ignored, which would
    # generate something which cannot be generated again.
    fails $passgen -m master "a"
    fails $passgen --master master -d example.com -t user -p apple2
    fails $passgen -d example.com "a"
    fails $passgen -t user "a"
    test "$($passgen --help 2>&1 | grep -c -- '--master\|--domain\|--token' || true)" = 0
fi

# JSON output
test "$($passgen -r zero --json "[a-z]{4}")" = '[{"output":"aaaa"}]'
test "$($passgen -r zero --json -a 2 'a"\\')" = '[{"output":"a\"\\"},{"output":"a\"\\"}]'
$passgen --json --entropy "[a-z]{4}" | matches '\[\{"output":"[a-z]{4}","entropy":18\.80[0-9]*\}\]'

# entropy
test "$($passgen -e "[a-z]{4}" 2>&1 >/dev/null)" = "entropy: 18.80 bits"

# also for more than fits into a double as a number of possibilities
test "$($passgen -e "[a-z]{300}" 2>&1 >/dev/null)" = "entropy: 1410.13 bits"
$passgen --json --entropy "[a-z]{300}" | matches '\[\{"output":"[a-z]+","entropy":1410\.13[0-9]*\}\]'

# wordlists
printf 'alpha\nbravo\ncharlie\n' > "$tmpdir/words.txt"
: > "$tmpdir/empty.txt"
$passgen -w "test:$tmpdir/words.txt" '\w{test}' | matches "(alpha|bravo|charlie)"
$passgen -w "test:$tmpdir/words.txt" '\w{test}(-\w{test}){3}' | matches "[a-z]+(-[a-z]+){3}"
$passgen -w "test:$tmpdir/words.txt" '\m{test}' | matches "[a-z]+"
$passgen -w "test:$tmpdir/words.txt" -M 2 '\m{test}' | matches "[a-z]+"

# user-defined presets and configuration file
test "$($passgen -P "mine:abc" -p mine)" = "abc"
echo "preset fromconfig:xyz" > "$XDG_CONFIG_HOME/passgen.conf"
test "$($passgen -p fromconfig)" = "xyz"
rm "$XDG_CONFIG_HOME/passgen.conf"
mkdir -p "$HOME/.config"
echo "preset fromhome:uvw" > "$HOME/.config/passgen.conf"
test "$(XDG_CONFIG_HOME= $passgen -p fromhome)" = "uvw"

# presets can use other presets, so that they can be built from parts. those
# whose names start with a dot are not listed, but work the same otherwise.
fragments=(-P '.segment:[a-z]{6}' -P 'joined:(\p{.segment}-){2}\p{.segment}')
$passgen "${fragments[@]}" '\p{joined}' | matches "[a-z]{6}-[a-z]{6}-[a-z]{6}"
$passgen "${fragments[@]}" -p joined | matches "[a-z]{6}-[a-z]{6}-[a-z]{6}"
$passgen "${fragments[@]}" -p .segment | matches "[a-z]{6}"
$passgen "${fragments[@]}" 'x\p{.segment}{2}' | matches "x[a-z]{12}"
test "$($passgen "${fragments[@]}" -l | grep -c segment)" = 1
test "$($passgen "${fragments[@]}" -l | grep -c '^preset joined ')" = 1
$passgen '\p{apple1}' | matches "([a-zA-Z0-9]{3}-){3}[a-zA-Z0-9]{3}"
# a preset is the same as its pattern in parentheses.
test "$($passgen -r xorshift:1 '\p{uuid}')" = "$($passgen -r xorshift:1 "($($passgen -l | sed -n 's/^preset uuid //p'))")"
# also from the configuration file, where the order does not matter, as they
# are only used once all of them are defined.
printf 'preset fromconfig:\\p{.part}\\p{.part}\npreset .part:[xy]\n' > "$XDG_CONFIG_HOME/passgen.conf"
$passgen -p fromconfig | matches "[xy]{2}"
rm "$XDG_CONFIG_HOME/passgen.conf"

# groups can be nested up to 1024 deep. more is an error in the pattern (exit
# status 3), also for patterns nested so deeply that freeing them used to run
# out of stack.
function nested() {
    printf '(%.0s' $(seq "$1")
    printf a
    printf ')%.0s' $(seq "$1")
}
$passgen "$(nested 1024)" | matches "a"
fails $passgen "$(nested 1025)"
$passgen "$(nested 1025)" >/dev/null 2>&1 || test "$?" = 3
fails $passgen "$(nested 50000)"
$passgen "$(nested 50000)" >/dev/null 2>&1 || test "$?" = 3

# --depth was removed, as the depth is limited when parsing.
fails $passgen -D 5 "a"

# step limit: every character of a set, run of literals, and group is a step,
# and the default is a million.
$passgen -S 20 "[a-z]{20}" | matches "[a-z]{20}"
fails $passgen -S 19 "[a-z]{20}"
$passgen --steps 6 "([ab]){3}" | matches "[ab]{3}"
fails $passgen --steps 5 "([ab]){3}"
test "$($passgen "(a{1000}){999}" | tr -d '\n' | wc -c)" -eq 999000
fails $passgen "(a{1000}){1000}"
fails $passgen "(){999999999}"
for steps in 0 -1 abc 5x "" " 5" 99999999999999999999999; do
    fails $passgen -S "$steps" "a"
    $passgen -S "$steps" a >/dev/null 2>&1 || test "$?" = 13
done

fails $passgen "a{5,2}"
fails $passgen "(abc"
fails $passgen "[z-a]"
fails $passgen "[]"
fails $passgen "[a-]"
fails $passgen "[a-z0-9-_]"
$passgen "[a\\-]{16}" | matches "[a-]{16}"
fails $passgen "a{}"
fails $passgen "{}a|b"
$passgen "a{,3}" | matches "a{0,3}"
fails $passgen "a[]{3}"
fails $passgen -a 0 "a"
fails $passgen -M 0 "a"
fails $passgen -M 1000 "a"
fails $passgen -p doesnotexist
fails $passgen -P "nocolon" "a"
fails $passgen -r nonsense "a"
fails $passgen -r xorshift: "a"
fails $passgen -r "file:$tmpdir/doesnotexist" "a"
fails $passgen -w "nocolon" "a"
fails $passgen -w "test:$tmpdir/doesnotexist" "a"
fails $passgen -w "test:$tmpdir/empty.txt" '\w{test}'
fails $passgen -w "test:$tmpdir/empty.txt" '\m{test}'
fails $passgen '\w{undefined}'
fails $passgen --json '\w{undefined}'
fails $passgen --nonexistent-option
fails $passgen "a" "b"
fails $passgen -p apple1 "a"

# errors say what is wrong. the colors are left out for comparing.
function error_of() {
    "$@" 2>&1 >/dev/null | sed $'s/\033\\[[0-9;]*m//g' | head -n 1
}

# all of what is printed as the error.
function error_lines() {
    "$@" 2>&1 >/dev/null | sed $'s/\033\\[[0-9;]*m//g' || true
}

test "$(error_of $passgen '[]')" = "error in pattern: set is empty"
test "$(error_of $passgen '(abc')" = "error in pattern: group is not closed"
test "$(error_of $passgen 'a{5,2}')" = "error in pattern: invalid repetition"
test "$(error_of $passgen 'a\q')" = "error in pattern: unknown escape sequence"

# a randomness source which cannot be used is named, but what may be a secret
# in it (a key or a master passphrase) is not printed, also for an unknown kind
# which may be a typo of one with a secret.
test "$(error_of $passgen -r "chacha20:secretkey" a)" = "error: cannot use randomness source 'chacha20:...'"
test "$(error_of $passgen -r "chacha20-argon2:$(printf 'x%.0s' $(seq 200))" a)" = "error: cannot use randomness source 'chacha20-argon2:...'"
test "$(error_of $passgen -r "chacha:secretkey" a)" = "error: cannot use randomness source 'chacha:...'"
test "$(error_lines $passgen -r "chacha20:secretkey" a | grep -c secretkey)" = 0
echo "random chacha20:secretkey" > "$XDG_CONFIG_HOME/passgen.conf"
test "$(error_lines $passgen a | grep -c secretkey)" = 0
rm "$XDG_CONFIG_HOME/passgen.conf"
# sources without secrets are printed in full.
test "$(error_of $passgen -r "file:/nonexistent" a)" = "error: cannot use randomness source 'file:/nonexistent'"
test "$(error_of $passgen -r "xorshift:0" a)" = "error: cannot use randomness source 'xorshift:0'"
test "$(error_of $passgen '\w{}')" = "error in pattern: expected a name in braces"
test "$(error_of $passgen '\w{undefined}')" = "error in pattern: wordlist not found: undefined"
test "$(error_of $passgen '\m{undefined}')" = "error in pattern: wordlist not found: undefined"
test "$(error_of $passgen -w "test:$tmpdir/empty.txt" '\w{test}')" = "error in pattern: wordlist is empty: test"
test "$(error_of $passgen 'a\p{name}')" = "error in pattern: preset not found: name"
fails $passgen 'a\p{name}'
fails $passgen -P 'a:\p{a}' 'x\p{a}'
fails $passgen -P 'a:\p{b}' -P 'b:(\p{a})' -p a
test "$(error_of $passgen -P 'a:x\p{a}?' '\p{a}')" = "error in pattern: preset cannot be used: a"
test "$(error_lines $passgen -P 'a:x\p{a}?' '\p{a}' | sed -n 2p)" = "caused by: preset uses itself: a"
# a problem in a preset is marked in the pattern of the preset as well.
output="$(error_lines $passgen -P '.part:[a-z' -P 'outer:ab\p{.part}' 'x\p{outer}')"
test "$(echo "$output" | sed -n 1p)" = "error in pattern: preset cannot be used: outer"
test "$(echo "$output" | sed -n 2p)" = "caused by: preset cannot be used: .part"
test "$(echo "$output" | sed -n 3p)" = "caused by: set is not closed"
test "$(echo "$output" | sed -n 6p)" = "preset outer: ab\p{.part}"
test "$(echo "$output" | sed -n 7p)" = "                ^^^^^^^^^"
test "$(echo "$output" | sed -n 8p)" = "preset .part: [a-z"
test "$(echo "$output" | sed -n 9p)" = "                  ^"
# presets which are broken don't matter unless they are used.
$passgen -P 'broken:[' -P 'fine:abc' -p fine | matches abc

# problems with wordlists point to where they are used, and come up before
# anything is generated (so also when it is not used in the end).
test "$(error_lines $passgen 'ab\w{undefined}c' | sed -n 3p)" = "           ^^^^^^^^^^^^^"
test -z "$($passgen -a 3 'a(b|\w{undefined}){0}' 2>/dev/null)"
test "$(error_of $passgen "$(nested 1025)")" = "error in pattern: nested too deeply"
test "$(error_of $passgen '{0}a')" = "error: nothing to choose from"
test "$(error_of $passgen "(){999999999}")" = "error: takes too many steps"
test "$(error_of $passgen -S 0 a)" = "error: illegal number of steps entered (0)"

# a wordlist which cannot be read (a pipe cannot be rewound) says why.
if [ -e /dev/stdin ]; then
    output="$(echo word | error_lines $passgen -w test:/dev/stdin '\w{test}')"
    test "$(echo "$output" | sed -n 1p)" = "error in pattern: wordlist could not be read: test"
    echo "$output" | sed -n 2p | grep -q "^caused by: cannot read file: "
    echo word | fails $passgen -w test:/dev/stdin '\m{test}'
fi

# a file which runs out is an error, with no output. one which is too short
# to start with is not opened. 1024 bytes are read at a time.
head -c 1500 /dev/zero > "$tmpdir/short.bin"
head -c 100 /dev/zero > "$tmpdir/tiny.bin"
test "$($passgen -r "file:$tmpdir/short.bin" '[a-z]{8}')" = "aaaaaaaa"
test "$(error_of $passgen -r "file:$tmpdir/short.bin" '[a-z]{200}')" = "error: source of randomness ran out"
test -z "$($passgen -r "file:$tmpdir/short.bin" '[a-z]{200}' 2>/dev/null || true)"
test -z "$($passgen -j -r "file:$tmpdir/short.bin" '[a-z]{200}' 2>/dev/null || true)"
fails $passgen -r "file:$tmpdir/short.bin" '[a-z]{200}'
fails $passgen -r "file:$tmpdir/tiny.bin" 'a'
fails $passgen -r "file:$tmpdir/empty.txt" 'a'

set +x
echo "All CLI tests passed."
