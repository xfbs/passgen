#!/bin/bash
if test "$#" -lt 1; then
    echo "$0 <passgen cli path>"
    echo "Runs tests against the passgen binary."
    echo
    echo "Example:"
    echo "    mkdir build"
    echo "    cmake -S . -B build"
    echo "    cmake --build build"
    echo "    ./scripts/test-passgen-cli.sh ./build/src/cli/passgen"
    exit 0
fi
set -euxo pipefail

# which binary to test
passgen=$@

# don't let the configuration of whoever runs this influence the tests
tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT
export HOME="$tmpdir/home"
export XDG_CONFIG_HOME="$tmpdir/config"
mkdir -p "$HOME" "$XDG_CONFIG_HOME/passgen"
# this also keeps out the configuration of the system. the tests for where
# the configuration is looked for unset it.
export PASSGEN_CONFIG=

function matches() {
    grep -E "^$1$"
}

# errors say what is wrong. the colors are left out for comparing.
function error_of() {
    "$@" 2>&1 >/dev/null | sed $'s/\033\\[[0-9;]*m//g' | head -n 1
}

# all of what is printed as the error.
function error_lines() {
    "$@" 2>&1 >/dev/null | sed $'s/\033\\[[0-9;]*m//g' || true
}

# a configuration file which is not valid fails (exit status 14), and the
# error is printed, without the path of the file.
function config_error() {
    printf "$1" > "$tmpdir/bad.toml"
    fails $passgen -c "$tmpdir/bad.toml" a
    $passgen -c "$tmpdir/bad.toml" a >/dev/null 2>&1 || test "$?" = 14
    error_of $passgen -c "$tmpdir/bad.toml" a | sed "s|$tmpdir/||"
}

# things that should fail, and not print anything to standard output
function fails() {
    local output
    if output="$("$@" 2>/dev/null)"; then
        echo "expected failure: $*"
        exit 1
    fi
    test -z "$output"
}

function pattern_matches() {
    $passgen "$1" | matches "$1"
}

# writing to /dev/null works. with seccomp, checking whether the output is a
# terminal (which the C library does for character devices such as this one)
# used to kill the process.
$passgen "a" > /dev/null
$passgen -r zero "a" > /dev/null 2>&1
fails $passgen "[" 2> /dev/null

# test simple grammar
pattern_matches "a"
pattern_matches "a?"
pattern_matches "a{2}"
pattern_matches "a{1,2}"
pattern_matches "abc"
pattern_matches "abc|def"
pattern_matches "(abc)"
pattern_matches "(abc){2}"
pattern_matches "(abc){1,2}"
pattern_matches "(abc|def)"
pattern_matches "(abc|def){2}"
pattern_matches "(abc|def){1,2}"
pattern_matches "[a]"
pattern_matches "[ab]"
pattern_matches "[a-z]"
pattern_matches "[a-zA-Z0-9#]"
pattern_matches "[a-zA-Z0-9#]{2}"
pattern_matches "[a-zA-Z0-9#]{1,2}"

# characters with a meaning in patterns can be escaped
test "$($passgen 'a\(b\)\[c\]\{d\}e\|f\?')" = "a(b)[c]{d}e|f?"
$passgen '[\]\[\-]{8}' | matches '[][-]{8}'
$passgen '[+-\-]{8}' | matches '[+,-]{8}'

# test presets
$passgen -p apple1
$passgen -p apple2
$passgen -p firefox
$passgen -p uuid
$passgen -p edge

# test options
$passgen --amount 5 "a"
$passgen -a 5 "a"

$passgen --null "a"
$passgen -z "a"

$passgen --entropy "a"
$passgen -e "a"

$passgen --random "xorshift:1234" "a"
$passgen --random "zero" "a"
$passgen --random "system" "a"

# test flags
$passgen --version
$passgen -v

$passgen --help
$passgen -h

$passgen --list
$passgen -l

# output is not limited in length
test "$($passgen "a{1000}" | tr -d '\n' | wc -c)" -eq 1000
test "$($passgen -a 3 "[a-z]{500}" | wc -l)" -eq 3

# outputs are separated by newlines (or NUL bytes), with a newline after the
# last one.
test "$($passgen -a 3 a | od -An -c | tr -d ' ')" = 'a\na\na\n'
test "$($passgen -z -a 3 a | od -An -c | tr -d ' ')" = 'a\0a\0a\n'

# the entropy of every output comes before it, also where both go to the same
# place. through a pipe, standard output is buffered, standard error is not.
test "$($passgen -e -a 3 '[ab]' 2>&1 | sed 's/^[ab]$/x/')" = "$(printf 'entropy: 1.00 bits\nx\nentropy: 1.00 bits\nx\nentropy: 1.00 bits\nx')"

# large outputs work when only little memory may be locked. the subshell keeps
# the limit from applying to the rest of the tests, and this is skipped where
# the limit cannot be set to this value. it takes more than the default
# limit of steps.
if (ulimit -l 8192) 2> /dev/null; then
    test "$(ulimit -l 8192; $passgen -S 20000000 "a{20000000}" | tr -d '\n' | wc -c)" -eq 20000000
fi

# deterministic randomness sources always produce the same output
test "$($passgen -r xorshift:1234 "[a-z]{32}")" = "$($passgen -r xorshift:1234 "[a-z]{32}")"
test "$($passgen -r zero "[a-z]{8}")" = "aaaaaaaa"

# every preset generates what the reference implementation says it should.
# this table is generated by `scripts/reference-vectors.py --cli`.
while read -r preset expected; do
    test "$($passgen -r xorshift:1234 -p "$preset")" = "$expected"
done << EOF
apple1 Rx3-t8Q-jsO-w2M
apple2 Rx3t8Q-jsOw2M-oCOmGr
uuid bb378ad6-8a26-42c8-8056-cb0cc9fe064b
edge P27OM1KAME5fEfA
firefox Rx3t8QjsOw2MoCO
proquint16 rugum
proquint32 rugum-pikap
proquint48 rugum-pikap-fofam
proquint64 rugum-pikap-fofam-bajos
proquint80 rugum-pikap-fofam-bajos-rasan
proquint96 rugum-pikap-fofam-bajos-rasan-zoboh
proquint112 rugum-pikap-fofam-bajos-rasan-zoboh-rokik
proquint128 rugum-pikap-fofam-bajos-rasan-zoboh-rokik-zohif
EOF
test "$($passgen --list | wc -l)" -eq 13

# master passphrase mode is deterministic, and depends on all of its inputs.
# these only work when built with monocypher (the default).
key="000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f"
if $passgen -r "chacha20:$key" "a" > /dev/null 2>&1; then
    a="$($passgen -r "master:1:1:master::example.com:user" -p apple2)"

    # known answer, to notice when the derivation changes (which would change
    # everyone's passwords). this is from scripts/reference-vectors.py.
    test "$a" = "cwlrWj-PcuVGE-OlCunW"
    # every sequence is generated from its own stream, which --offset starts
    # at, and which is what the reference implementation says for them.
    test "$($passgen -r "master:1:1:master::example.com:user" -a 3 -p apple2 | head -n 1)" = "$a"
    test "$($passgen -r "master:1:1:master::example.com:user" -a 3 -p apple2 | sed -n 3p)" = \
        "$($passgen -r "master:1:1:master::example.com:user" --offset 2 -p apple2)"

    test "$a" != "$($passgen -r "master:1:1:other::example.com:user" -p apple2)"
    test "$a" != "$($passgen -r "master:1:1:master::example.org:user" -p apple2)"
    test "$a" != "$($passgen -r "master:1:1:master::example.com:admin" -p apple2)"
    test "$a" != "$($passgen -r "master:1:1:master:00:example.com:user" -p apple2)"
    test "$a" != "$($passgen -r "master:1:2:master::example.com:user" -p apple2)"
    # colons and backslashes in the fields are escaped.
    $passgen -r 'master:1:1:pass\:word\\::example.com\:8443:user' -p apple2 | matches "([a-zA-Z0-9]{6}-){2}[a-zA-Z0-9]{6}"
    fails $passgen -r 'master:1:1:pa\ss::example.com:user' a
    fails $passgen -r 'master:1:1:master::example.com' a
    fails $passgen -r 'master:2:1:master::example.com:user' a
    fails $passgen -r 'master:1:4:master::example.com:user' a

    # a master passphrase is set up for the configuration, and then used by
    # its name. it is read from standard input, which is not a terminal here.
    echo master | $passgen --master-setup main --master-level 1 --master-version 1 > "$tmpdir/master.toml"
    test "$(cat "$tmpdir/master.toml")" = '[master.main]
version = 1
level = 1
hash = "fd915731"'
    test "$(echo master | $passgen -c "$tmpdir/master.toml" -m main -d example.com -u user -p apple2)" = "$a"
    test "$(echo master | $passgen -c "$tmpdir/master.toml" --master main --domain example.com --user user -p apple2)" = "$a"
    test "$(echo master | $passgen -c "$tmpdir/master.toml" -m main -d example.com -u user --offset 2 -p apple2)" = \
        "$($passgen -r "master:1:1:master::example.com:user" --offset 2 -p apple2)"
    # without a terminal to ask at, the level is 2, and there is no seed.
    test "$(echo master | $passgen --master-setup main)" = '[master.main]
version = 1
level = 2
hash = "e1581cf7"'
    # the name can also be given as --master-setup=name, and is main if it is
    # not given (and there is no terminal to ask at).
    test "$(echo master | $passgen --master-setup=other --master-level 1 | head -n 1)" = '[master.other]'
    test "$(echo master | $passgen --master-setup --master-level 1 | head -n 1)" = '[master.main]'
    fails sh -c "echo master | $passgen --master-setup= --master-level 1"
    fails sh -c "echo master | $passgen --master-setup=main --master-level 1 extra"
    fails sh -c "echo master | $passgen --master-setup \"\$(printf 'a\tb')\" --master-level 1"
    # names which are not bare keys are quoted.
    test "$(echo master | $passgen --master-setup 'my "key"' --master-level 1 | head -n 1)" = '[master."my \"key\""]'

    # the hash tells a wrong master passphrase apart, which is an error (exit
    # status 15), as are a missing one and one which is not configured.
    fails sh -c "echo other | $passgen -c $tmpdir/master.toml -m main -p apple2"
    test "$(echo other | error_of $passgen -c "$tmpdir/master.toml" -m main -p apple2)" = "error: wrong master passphrase for \`main\`"
    (echo other | $passgen -c "$tmpdir/master.toml" -m main -p apple2 >/dev/null 2>&1) || test "$?" = 15
    test "$(error_of $passgen -c "$tmpdir/master.toml" -m main -p apple2 < /dev/null)" = "error: no master passphrase was entered"
    test "$(echo | error_of $passgen -c "$tmpdir/master.toml" -m main -p apple2)" = "error: the master passphrase is empty"
    test "$(echo master | error_of $passgen -c "$tmpdir/master.toml" -m other -p apple2)" = "error: there is no master passphrase \`other\` in the configuration, see --master-setup"
    # an invalid pattern is noticed before the master passphrase is asked for.
    test "$(error_of $passgen -c "$tmpdir/master.toml" -m main '[' < /dev/null)" = "error in pattern: set is not closed"

    # any prefix of the hash works, in either case, and so does none.
    printf '[master.main]\nversion = 1\nlevel = 1\nhash = "FD9"\n' > "$tmpdir/master2.toml"
    test "$(echo master | $passgen -c "$tmpdir/master2.toml" -m main -d example.com -u user -p apple2)" = "$a"
    printf '[master.main]\nversion = 1\nlevel = 1\n' > "$tmpdir/master2.toml"
    test "$(echo master | $passgen -c "$tmpdir/master2.toml" -m main -d example.com -u user -p apple2)" = "$a"
    test "$(echo other | $passgen -c "$tmpdir/master2.toml" -m main -d example.com -u user -p apple2)" != "$a"
    # a later file can remove it.
    printf '[master]\nmain = false\n' > "$tmpdir/master3.toml"
    fails sh -c "echo master | $passgen -c $tmpdir/master.toml -c $tmpdir/master3.toml -m main a"

    # with a seed, it is the same as with the seed in the description.
    echo master | $passgen --master-setup main --master-level 1 --master-seed > "$tmpdir/seeded.toml"
    grep -q '^# keep this safe, and back it up$' "$tmpdir/seeded.toml"
    seed="$(sed -n 's/^seed = "\(.*\)"$/\1/p' "$tmpdir/seeded.toml")"
    test "${#seed}" = 32
    test "$(echo master | $passgen -c "$tmpdir/seeded.toml" -m main -d example.com -u user -p apple2)" = \
        "$($passgen -r "master:1:1:master:$seed:example.com:user" -p apple2)"
    test "$(echo master | $passgen -c "$tmpdir/seeded.toml" -m main -d example.com -u user -p apple2)" != "$a"

    # problems with master passphrases in the configuration.
    test "$(config_error '[master.main]\nversion = 1\n')" = "error: in configuration \`bad.toml\`: (line 1) master passphrase \`main\` needs a version and a level"
    test "$(config_error '[master.main]\nversion = 2\nlevel = 1\n')" = "error: in configuration \`bad.toml\`: (line 2) master passphrase \`main\` has to have version 1"
    test "$(config_error '[master.main]\nversion = 1\nlevel = 4\n')" = "error: in configuration \`bad.toml\`: (line 3) master passphrase \`main\` has to have a level from 1 to 3"
    test "$(config_error '[master.main]\nversion = 1\nlevel = 1\nhash = "xyz"\n')" = "error: in configuration \`bad.toml\`: (line 4) the hash of master passphrase \`main\` has to be 1 to 64 hex digits"
    test "$(config_error '[master.main]\nversion = 1\nlevel = 1\nseed = "abc"\n')" = "error: in configuration \`bad.toml\`: (line 4) the seed of master passphrase \`main\` has to be up to 64 bytes in hex"
    test "$(config_error '[master.main]\nversion = 1\nlevel = 1\ntoken = "x"\n')" = "error: in configuration \`bad.toml\`: (line 4) unknown key \`token\` in master passphrase \`main\`"
    test "$(config_error '[master]\nmain = "x"\n')" = "error: in configuration \`bad.toml\`: (line 2) master passphrase \`main\` has to be a table, or false"

    # logins say which master passphrase, pattern and offset a domain and a
    # user use, which then only need -d and -u.
    cat "$tmpdir/master.toml" > "$tmpdir/logins.toml"
    cat >> "$tmpdir/logins.toml" <<'TOML'

[[login]]
domain = "example.com"
user = "user"
preset = "apple2"

[[login]]
domain = "example.com"
user = "admin"
master = "main"
pattern = '[a-z]{12}'
offset = 2

[[login]]
domain = "example.org"
preset = "uuid"
TOML
    logins="$tmpdir/logins.toml"
    test "$(echo master | $passgen -c "$logins" -d example.com -u user)" = "$a"
    test "$(echo master | $passgen -c "$logins" -d example.com -u admin)" = \
        "$($passgen -r "master:1:1:master::example.com:admin" --offset 2 '[a-z]{12}')"
    # with only one login for a domain, the user is not needed.
    test "$(echo master | $passgen -c "$logins" -d example.org)" = \
        "$($passgen -r "master:1:1:master::example.org:" -p uuid)"
    # what is given on the command line takes precedence.
    test "$(echo master | $passgen -c "$logins" -d example.com -u user '[0-9]{8}')" = \
        "$($passgen -r "master:1:1:master::example.com:user" '[0-9]{8}')"
    test "$(echo master | $passgen -c "$logins" -d example.com -u admin --offset 0)" = \
        "$($passgen -r "master:1:1:master::example.com:admin" '[a-z]{12}')"
    test "$(echo master | $passgen -c "$logins" -d example.com -u user -a 2 | tail -n 1)" = \
        "$($passgen -r "master:1:1:master::example.com:user" --offset 1 -p apple2)"
    # with a master passphrase, a domain without a login works as always.
    test "$(echo master | $passgen -c "$logins" -m main -d example.com -u user -p apple2)" = "$a"
    test "$(echo master | $passgen -c "$logins" -m main -d example.net -p apple2)" = \
        "$($passgen -r "master:1:1:master::example.net:" -p apple2)"
    # which login is meant has to be clear, and there has to be one.
    test "$(echo master | error_of $passgen -c "$logins" -d example.com)" = "error: there is more than one login for \`example.com\`, choose one with --user: \`user\`, \`admin\`"
    test "$(echo master | error_of $passgen -c "$logins" -d example.net)" = "error: there is no login for \`example.net\` in the configuration, give --master"
    test "$(echo master | error_of $passgen -c "$logins" -d example.com -u nobody)" = "error: there is no login for \`example.com\` and user \`nobody\` in the configuration, give --master"
    test "$(echo master | error_of $passgen -c "$logins" -m main -d example.net)" = "error: there is no login for \`example.net\` which says which pattern to use, give one"
    (echo master | $passgen -c "$logins" -d example.net >/dev/null 2>&1) || test "$?" = 15
    fails $passgen -c "$logins" -r zero -d example.com -u user
    fails $passgen -c "$logins" -u user a
    # without a master passphrase in it, a login uses the only one there is.
    printf '[master.other]\nversion = 1\nlevel = 1\n' > "$tmpdir/second.toml"
    test "$(echo master | error_of $passgen -c "$logins" -c "$tmpdir/second.toml" -d example.com -u user)" = "error: the login for \`example.com\` does not say which master passphrase it uses, and there is more than one, give --master"
    test "$(echo master | $passgen -c "$logins" -c "$tmpdir/second.toml" -d example.com -u admin)" = \
        "$($passgen -r "master:1:1:master::example.com:admin" --offset 2 '[a-z]{12}')"

    # problems with logins in the configuration.
    test "$(config_error '[[login]]\nuser = "a"\n')" = "error: in configuration \`bad.toml\`: (line 1) a login needs a domain"
    test "$(config_error '[[login]]\ndomain = "a"\npreset = "x"\npattern = "y"\n')" = "error: in configuration \`bad.toml\`: (line 1) a login can have a preset or a pattern, not both"
    test "$(config_error '[[login]]\ndomain = "a"\noffset = -1\n')" = "error: in configuration \`bad.toml\`: (line 3) the offset of a login has to be a number, from 0"
    test "$(config_error '[[login]]\ndomain = 1\n')" = "error: in configuration \`bad.toml\`: (line 2) \`domain\` of a login has to be a string"
    test "$(config_error '[[login]]\ndomain = "a"\ntoken = "b"\n')" = "error: in configuration \`bad.toml\`: (line 3) unknown key \`token\` in a login"
    test "$(config_error '[login]\ndomain = "a"\n')" = "error: in configuration \`bad.toml\`: (line 1) \`login\` has to be an array of tables, as [[login]]"
    test "$(config_error '[[login]]\ndomain = "a"\n[[login]]\ndomain = "a"\n')" = "error: in configuration \`bad.toml\`: (line 3) there is another login for \`a\` without a user, in \`$tmpdir/bad.toml\`"
    printf '[[login]]\ndomain = "example.com"\nuser = "user"\n' > "$tmpdir/again.toml"
    test "$(error_of $passgen -c "$logins" -c "$tmpdir/again.toml" a | sed "s|$tmpdir/||g")" = "error: in configuration \`again.toml\`: (line 1) there is another login for \`example.com\` and user \`user\`, in \`logins.toml\`"

    # wordlists can be checked to have the hash they are meant to have, as
    # b2sum prints it, or any start of it.
    mkdir -p "$tmpdir/conf/lists"
    printf 'alpha\nbravo\ncharlie\n' > "$tmpdir/conf/lists/hashed.txt"
    hash="69aef28a24eff680a03c73da91b961d4e77455aadb6fad1ac7d423d8d1a094f7391598b8136078ba96d55ac17aedd11e6031a9be7c53413c517f5b22210891da"
    cat > "$tmpdir/conf/hashed.toml" <<TOML
[wordlists]
full = { path = "lists/hashed.txt", hash = "$hash" }
short = { path = "lists/hashed.txt", hash = "69AEF28A" }
wrong = { path = "lists/hashed.txt", hash = "69aef28b" }

[wordlists.table]
path = "lists/hashed.txt"
hash = "69aef28a24"
TOML
    hashed="$tmpdir/conf/hashed.toml"
    for name in full short table; do
        $passgen -c "$hashed" "\\w{$name}" | matches "(alpha|bravo|charlie)"
    done
    $passgen -c "$hashed" a | matches a
    fails $passgen -c "$hashed" '\w{wrong}'
    test "$(error_lines $passgen -c "$hashed" '\w{wrong}' | head -n 2)" = "error in pattern: wordlist could not be read: wrong
caused by: does not have the expected hash"
    printf 'alpha\nbravo\n' > "$tmpdir/conf/lists/hashed.txt"
    fails $passgen -c "$hashed" '\w{full}'
    test "$(config_error '[wordlists]\nx = { path = "a", hash = "xyz" }\n')" = "error: in configuration \`bad.toml\`: (line 2) the hash of wordlist \`x\` has to be 1 to 128 hex digits, as b2sum prints it"
    test "$(config_error '[wordlists]\nx = { hash = "ab" }\n')" = "error: in configuration \`bad.toml\`: (line 2) wordlist \`x\` has to be a path, a table with a path (and a hash), or false"
    test "$(config_error '[wordlists]\nx = { path = "a", size = 1 }\n')" = "error: in configuration \`bad.toml\`: (line 2) wordlist \`x\` can only have a path and a hash, which are strings"

    # it is a source of randomness itself, so giving another one is a
    # mistake, as are a domain or a user without a master passphrase, and
    # options for setting one up without doing so.
    fails $passgen -c "$tmpdir/master.toml" -m main -r zero "a"
    fails $passgen -c "$tmpdir/master.toml" -r zero -m main "a"
    fails $passgen -d example.com "a"
    fails $passgen -u user "a"
    fails $passgen --master-level 2 "a"
    fails $passgen --master-seed "a"
    fails $passgen --master-version 1 "a"
    fails sh -c "echo master | $passgen --master-setup main a"
    fails sh -c "echo master | $passgen --master-setup main --master-level 4"
    fails sh -c "echo master | $passgen --master-setup main --master-version 2"
    fails $passgen --level 2 "a"
    fails $passgen --seed "a"
    fails sh -c "echo master | $passgen --master-setup main -m main"

    # deriving the key needs more memory than may commonly be locked
    if (ulimit -l 8192) 2> /dev/null; then
        test "$a" = "$(ulimit -l 8192; $passgen -r "master:1:1:master::example.com:user" -p apple2)"
    fi

    # the key and IV of chacha20 are exactly 64 and 16 hex digits, and the
    # default IV is `passgen` followed by a zero byte.
    test "$($passgen -r "chacha20:$key" "[a-z]{16}")" = \
        "$($passgen -r "chacha20:$key:7061737367656e00" "[a-z]{16}")"
    test "$($passgen -r "chacha20:$key" "[a-z]{16}")" != \
        "$($passgen -r "chacha20:$key:0000000000000000" "[a-z]{16}")"
    fails $passgen -r "chacha20:key" "a"
    fails $passgen -r "chacha20:${key}0" "a"
    fails $passgen -r "chacha20:$key:" "a"
    fails $passgen -r "chacha20:$key:00000000" "a"

    # overlong keys are rejected
    long="$(printf 'A%.0s' $(seq 1 300))"
    fails $passgen -r "chacha20:$long" "a"
    fails $passgen -r "master:1:1:$long::example.com:user" "a"
else
    # without monocypher, the options for master passphrase mode do not
    # exist, so using them is an error rather than being ignored, which would
    # generate something which cannot be generated again.
    fails $passgen -m main "a"
    fails $passgen --master main -d example.com -u user -p apple2
    fails $passgen -d example.com "a"
    fails $passgen -u user "a"
    fails $passgen --master-setup main
    test "$($passgen --help 2>&1 | grep -c -- '--master\|--domain\|--user' || true)" = 0
    # hashes of wordlists cannot be checked, so they are ignored.
    mkdir -p "$tmpdir/conf/lists"
    printf 'alpha\n' > "$tmpdir/conf/lists/hashed.txt"
