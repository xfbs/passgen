#!/bin/bash
if test "$#" -lt 1; then
    echo "$0 <passgen cli path>"
    echo "Runs tests against the passgen binary."
    echo
    echo "Example:"
    echo "    mkdir build"
    echo "    cmake -S . -B build"
    echo "    cmake --build build"
    echo "    ./scripts/test-passgen-cli.sh ./build/src/cli/passgen"
    exit 0
fi
set -euxo pipefail

# which binary to test
passgen=$@

# don't let the configuration of whoever runs this influence the tests
tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT
export HOME="$tmpdir/home"
export XDG_CONFIG_HOME="$tmpdir/config"
unset XDG_CONFIG_PATH
mkdir -p "$HOME" "$XDG_CONFIG_HOME"

function matches() {
    grep -E "^$1$"
}

# things that should fail, and not print anything to standard output
function fails() {
    local output
    if output="$("$@" 2>/dev/null)"; then
        echo "expected failure: $*"
        exit 1
    fi
    test -z "$output"
}

function pattern_matches() {
    $passgen "$1" | matches "$1"
}

# test simple grammar
pattern_matches "a"
pattern_matches "a?"
pattern_matches "a{2}"
pattern_matches "a{1,2}"
pattern_matches "abc"
pattern_matches "abc|def"
pattern_matches "(abc)"
pattern_matches "(abc){2}"
pattern_matches "(abc){1,2}"
pattern_matches "(abc|def)"
pattern_matches "(abc|def){2}"
pattern_matches "(abc|def){1,2}"
pattern_matches "[a]"
pattern_matches "[ab]"
pattern_matches "[a-z]"
pattern_matches "[a-zA-Z0-9#]"
pattern_matches "[a-zA-Z0-9#]{2}"
pattern_matches "[a-zA-Z0-9#]{1,2}"

# characters with a meaning in patterns can be escaped
test "$($passgen 'a\(b\)\[c\]\{d\}e\|f\?')" = "a(b)[c]{d}e|f?"
$passgen '[\]\[\-]{8}' | matches '[][-]{8}'
$passgen '[+-\-]{8}' | matches '[+,-]{8}'

# test presets
$passgen -p apple1
$passgen -p apple2
$passgen -p firefox
$passgen -p uuid
$passgen -p edge

# test options
$passgen --amount 5 "a"
$passgen -a 5 "a"

$passgen --null "a"
$passgen -z "a"

$passgen --entropy "a"
$passgen -e "a"

$passgen --random "xorshift:1234" "a"
$passgen --random "zero" "a"
$passgen --random "system" "a"

# test flags
$passgen --version
$passgen -v

$passgen --help
$passgen -h

$passgen --list
$passgen -l

# output is not limited in length
test "$($passgen "a{1000}" | tr -d '\n' | wc -c)" -eq 1000
test "$($passgen -a 3 "[a-z]{500}" | wc -l)" -eq 3

# large outputs work when only little memory may be locked. the subshell keeps
# the limit from applying to the rest of the tests, and this is skipped where
# the limit cannot be set to this value.
if (ulimit -l 8192) 2> /dev/null; then
    test "$(ulimit -l 8192; $passgen "a{20000000}" | tr -d '\n' | wc -c)" -eq 20000000
fi

# deterministic randomness sources always produce the same output
test "$($passgen -r xorshift:1234 "[a-z]{32}")" = "$($passgen -r xorshift:1234 "[a-z]{32}")"
test "$($passgen -r zero "[a-z]{8}")" = "aaaaaaaa"

# every preset generates what the reference implementation says it should.
# this table is generated by `scripts/reference-vectors.py --cli`.
while read -r preset expected; do
    test "$($passgen -r xorshift:1234 -p "$preset")" = "$expected"
done << EOF
apple1 d3i-T2y-cwY-myW
apple2 d3iAT2-6cwYmy-Wq1gS7
uuid b378ad68-a262-4c80-856c-b0cc9fe064be
edge DIaYCWMYQG-Q-MP
firefox 7d3iAT2y6cwYmyW
proquint16 gupik
proquint32 gupik-fosab
proquint48 gupik-fosab-kabas
proquint64 gupik-fosab-kabas-vahuv
proquint80 gupik-fosab-kabas-vahuv-kuhif
proquint96 gupik-fosab-kabas-vahuv-kuhif-kufaf
proquint112 gupik-fosab-kabas-vahuv-kuhif-kufaf-zazut
proquint128 gupik-fosab-kabas-vahuv-kuhif-kufaf-zazut-gaboz
EOF
test "$($passgen --list | wc -l)" -eq 13

# master passphrase mode is deterministic, and depends on all of its inputs.
# these only work when built with monocypher (the default).
if $passgen -r chacha20:key "a" > /dev/null 2>&1; then
    a="$($passgen -m master -d example.com -t user -p apple2)"
    test "$a" = "$($passgen -m master -d example.com -t user -p apple2)"
    test "$a" != "$($passgen -m other -d example.com -t user -p apple2)"
    test "$a" != "$($passgen -m master -d example.org -t user -p apple2)"
    test "$a" != "$($passgen -m master -d example.com -t admin -p apple2)"

    # known answer, to notice when the derivation changes (which would change
    # everyone's passwords).
    test "$a" = "JuIHep-ZdR5yQ-Nq7cO2"

    # a randomness source from the configuration does not get in the way
    echo "random zero" > "$XDG_CONFIG_HOME/passgen.conf"
    test "$a" = "$($passgen -m master -d example.com -t user -p apple2)"
    rm "$XDG_CONFIG_HOME/passgen.conf"

    # but giving one on the command line is a mistake, as are a domain or a
    # token without a master passphrase
    fails $passgen -m master -r zero "a"
    fails $passgen -r zero -m master "a"
    fails $passgen -d example.com "a"
    fails $passgen -t user "a"

    # deriving the key needs more memory than may commonly be locked
    if (ulimit -l 8192) 2> /dev/null; then
        test "$a" = "$(ulimit -l 8192; $passgen -m master -d example.com -t user -p apple2)"
    fi

    # overlong keys are rejected
    long="$(printf 'A%.0s' $(seq 1 300))"
    fails $passgen -r "chacha20:$long" "a"
    fails $passgen -r "chacha20-argon2:$long" "a"
fi

# JSON output
test "$($passgen -r zero --json "[a-z]{4}")" = '[{"output":"aaaa"}]'
test "$($passgen -r zero --json -a 2 'a"\\')" = '[{"output":"a\"\\"},{"output":"a\"\\"}]'
$passgen --json --entropy "[a-z]{4}" | matches '\[\{"output":"[a-z]{4}","entropy":18\.80[0-9]*\}\]'

# entropy
test "$($passgen -e "[a-z]{4}" 2>&1 >/dev/null)" = "entropy: 18.80 bits"

# also for more than fits into a double as a number of possibilities
test "$($passgen -e "[a-z]{300}" 2>&1 >/dev/null)" = "entropy: 1410.13 bits"
$passgen --json --entropy "[a-z]{300}" | matches '\[\{"output":"[a-z]+","entropy":1410\.13[0-9]*\}\]'

# wordlists
printf 'alpha\nbravo\ncharlie\n' > "$tmpdir/words.txt"
: > "$tmpdir/empty.txt"
$passgen -w "test:$tmpdir/words.txt" '\w{test}' | matches "(alpha|bravo|charlie)"
$passgen -w "test:$tmpdir/words.txt" '\w{test}(-\w{test}){3}' | matches "[a-z]+(-[a-z]+){3}"
$passgen -w "test:$tmpdir/words.txt" '\m{test}' | matches "[a-z]+"
$passgen -w "test:$tmpdir/words.txt" -M 2 '\m{test}' | matches "[a-z]+"

# user-defined presets and configuration file
test "$($passgen -P "mine:abc" -p mine)" = "abc"
echo "preset fromconfig:xyz" > "$XDG_CONFIG_HOME/passgen.conf"
test "$($passgen -p fromconfig)" = "xyz"
rm "$XDG_CONFIG_HOME/passgen.conf"
mkdir -p "$HOME/.config"
echo "preset fromhome:uvw" > "$HOME/.config/passgen.conf"
test "$(XDG_CONFIG_HOME= $passgen -p fromhome)" = "uvw"

# depth limit
$passgen -D 5 "((((a))))" | matches "a"
fails $passgen -D 2 "((((a))))"

# the default limit is 1024 (and counts the pattern itself as one level).
function nested() {
    printf '(%.0s' $(seq "$1")
    printf a
    printf ')%.0s' $(seq "$1")
}
$passgen "$(nested 1023)" | matches "a"
fails $passgen "$(nested 1024)"

fails $passgen "a{5,2}"
fails $passgen "(abc"
fails $passgen "[z-a]"
fails $passgen "[]"
fails $passgen "[a-]"
fails $passgen "[a-z0-9-_]"
$passgen "[a\\-]{16}" | matches "[a-]{16}"
fails $passgen "a{}"
fails $passgen "{}a|b"
$passgen "a{,3}" | matches "a{0,3}"
fails $passgen "a[]{3}"
fails $passgen -a 0 "a"
fails $passgen -M 0 "a"
fails $passgen -M 1000 "a"
fails $passgen -D 0 "a"
fails $passgen -p doesnotexist
fails $passgen -P "nocolon" "a"
fails $passgen -r nonsense "a"
fails $passgen -r xorshift: "a"
fails $passgen -r "file:$tmpdir/doesnotexist" "a"
fails $passgen -w "nocolon" "a"
fails $passgen -w "test:$tmpdir/doesnotexist" "a"
fails $passgen -w "test:$tmpdir/empty.txt" '\w{test}'
fails $passgen -w "test:$tmpdir/empty.txt" '\m{test}'
fails $passgen '\w{undefined}'
fails $passgen --json '\w{undefined}'
fails $passgen --nonexistent-option
fails $passgen "a" "b"
fails $passgen -p apple1 "a"

# errors say what is wrong. the colors are left out for comparing.
function error_of() {
    "$@" 2>&1 >/dev/null | sed $'s/\033\\[[0-9;]*m//g' | head -n 1
}

# all of what is printed as the error.
function error_lines() {
    "$@" 2>&1 >/dev/null | sed $'s/\033\\[[0-9;]*m//g' || true
}

test "$(error_of $passgen '[]')" = "error in pattern: set is empty"
test "$(error_of $passgen '(abc')" = "error in pattern: group is not closed"
test "$(error_of $passgen 'a{5,2}')" = "error in pattern: invalid repetition"
test "$(error_of $passgen 'a\q')" = "error in pattern: unknown escape sequence"
test "$(error_of $passgen '\w{}')" = "error in pattern: expected a name in braces"
test "$(error_of $passgen '\w{undefined}')" = "error: wordlist not found: undefined"
test "$(error_of $passgen '\m{undefined}')" = "error: wordlist not found: undefined"
test "$(error_of $passgen -w "test:$tmpdir/empty.txt" '\w{test}')" = "error: wordlist is empty: test"
test "$(error_of $passgen -D 2 '((((a))))')" = "error: nested too deeply"
test "$(error_of $passgen '{0}a')" = "error: nothing to choose from"

# a wordlist which cannot be read (a pipe cannot be rewound) says why.
if [ -e /dev/stdin ]; then
    output="$(echo word | error_lines $passgen -w test:/dev/stdin '\w{test}')"
    test "$(echo "$output" | sed -n 1p)" = "error: wordlist could not be read: test"
    echo "$output" | sed -n 2p | grep -q "^caused by: cannot read file: "
    echo word | fails $passgen -w test:/dev/stdin '\m{test}'
fi

# a file which runs out is an error, with no output. one which is too short
# to start with is not opened. 1024 bytes are read at a time.
head -c 1500 /dev/zero > "$tmpdir/short.bin"
head -c 100 /dev/zero > "$tmpdir/tiny.bin"
test "$($passgen -r "file:$tmpdir/short.bin" '[a-z]{8}')" = "aaaaaaaa"
test "$(error_of $passgen -r "file:$tmpdir/short.bin" '[a-z]{200}')" = "error: source of randomness ran out"
test -z "$($passgen -r "file:$tmpdir/short.bin" '[a-z]{200}' 2>/dev/null || true)"
test -z "$($passgen -j -r "file:$tmpdir/short.bin" '[a-z]{200}' 2>/dev/null || true)"
fails $passgen -r "file:$tmpdir/short.bin" '[a-z]{200}'
fails $passgen -r "file:$tmpdir/tiny.bin" 'a'
fails $passgen -r "file:$tmpdir/empty.txt" 'a'

set +x
echo "All CLI tests passed."
